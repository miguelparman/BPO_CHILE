"""Constantes de negocio del proceso: origenes CSV, esquema de las tablas
temporales y el mapeo columna a columna del Data Flow 'CARGA'.

El bloque CARGA se genero automaticamente trazando el linaje del .dtsx
(OLE DB Source -> Conditional Split / Derived Column -> Data Conversion ->
OLE DB Destination) y cruzandolo con el esquema real de CL_TRAFICO
(INFORMATION_SCHEMA). tests/equivalencia/test_equivalencia_dtsx.py vuelve a
trazar el .dtsx y verifica que este archivo siga coincidiendo.

Nomenclatura de conversiones (tipos SSIS de la columna que llega al destino):
    DT_STR n        string no-Unicode (code page 1252) de largo n
    DT_WSTR n       string Unicode de largo n
    DT_I4           entero de 4 bytes
    DT_DBTIMESTAMP  fecha y hora
    DT_DBDATE       fecha
    None            la columna llega sin Data Conversion (mapeo directo)
Toda conversion es 'FailComponent' (un valor que no convierte o no cabe
aborta el paquete) salvo las marcadas con ignorar_fallo=True
('IgnoreFailure': el valor queda NULL).
"""

