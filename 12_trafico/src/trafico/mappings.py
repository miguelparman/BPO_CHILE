@dataclass(frozen=True)
class OrigenCsv:
    """Un Execute Process Task de la secuencia TEMPORALES (un script .py)."""

    paso: str  # nombre de la tarea en el .dtsx
    script_original: str  # script .py que ejecutaba la tarea
    archivo: str  # CSV en SharePoint (= nombre de la tabla de [Externos_Frac])
    tabla_temporal: str  # destino en CL_TEMPORALES
    columnas: tuple[str, ...]  # columnas que se insertan (el resto del CSV se ignora)
    columna_periodo: str  # columna del filtro del periodo
    # True: el filtro original era CONVERT(VARCHAR(6),[col],112) >= periodo
    # sobre un datetime; False: [col] >= periodo sobre un int YYYYMM.
    periodo_desde_fecha: bool = False
    # Como representar una celda vacia del CSV en las columnas de texto. El CSV
    # no distingue NULL de '': se eligio lo que tenia la tabla de origen
    # (verificado contra lo que dejo SSIS en CL_TEMPORALES): NULL en todas
    # salvo cross_inbound, que guardaba cadenas vacias.
    texto_vacio_como_null: bool = True
    # Columnas de texto (nvarchar) que en [Externos_Frac] eran datetime2(7):
    # SQL Server las guardaba con el formato 'YYYY-MM-DD HH:MM:SS.fffffff'.
    columnas_texto_datetime2: tuple[str, ...] = ()


