UPDATE [CL_TEMPORALES].[dbo].[TBL_TRAFICO_CALLBACK]
SET 
	[EMPRESA_LOGINID] = 
						CASE WHEN LEFT([AGENTE],4) = '5103' THEN 'FRACTALIA' 
						ELSE 'OTROS' END,

[TRAMO60MIN] = CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [FECHA]), '1900-01-01'), 'HH:00:00'),' - ',
                FORMAT(DATEADD(HOUR, DATEPART(HOUR, [FECHA]) + 1, '1900-01-01'), 'HH:00:00')),
[TRAMO30MIN] = CASE WHEN DATEPART(MINUTE, [FECHA]) <= 30 
                     THEN CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [FECHA]), '1900-01-01'), 'HH:00:00'),' - ',
				          FORMAT(DATEADD(HOUR, DATEPART(HOUR, [FECHA]), '1900-01-01'), 'HH:30:00'))
                     ELSE CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [FECHA]), '1900-01-01'), 'HH:30:00'),' - ',
				          FORMAT(DATEADD(HOUR,1,(DATEADD(HOUR, DATEPART(HOUR, [FECHA]), '1900-01-01'))), 'HH:00:00')) END,
[SERVICIO] = CASE WHEN CAST([FECHA] AS DATE)<'2024-05-14' AND [TIPO_CLIENTE] = 'C' THEN 'CARTERIZADOS'
                  WHEN CAST([FECHA] AS DATE)>='2024-05-14' AND [TIPO_CLIENTE] = 'Y' THEN 'CARTERIZADOS'
                  ELSE 'TRIADAS' END