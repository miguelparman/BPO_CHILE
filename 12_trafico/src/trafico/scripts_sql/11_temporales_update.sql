UPDATE [CL_TEMPORALES].[dbo].[TBL_TRAFICO_ATENDIDA]
  SET RUT_USUARIO = '-'
  WHERE RUT_USUARIO NOT LIKE '%[0-9]%'
  AND RUT_USUARIO <>''

UPDATE [CL_TEMPORALES].[dbo].[TBL_TRAFICO_ATENDIDA]
SET 
[LOGINID] = LEFT([LOGINID],8),
[STOP_ACTION] = LEFT([STOP_ACTION],1),
[PLACE] = SUBSTRING([PLACE],7,8),
[EMPRESA_LOGINID] = CASE WHEN LEFT([LOGINID],4) = '5103' THEN 'FRACTALIA' ELSE 'OTROS' END,
[SERVICIO] = CASE WHEN LEFT([PCRC_EAC],6) = 'TRIADA' THEN 'TRIADAS' 
                  WHEN LEFT([PCRC_EAC],9) = 'RETENCION' THEN 'RETENCIONES' 
				  WHEN LEFT([PCRC_EAC],9) = 'PYMES CAR' THEN 'CARTERIZADOS' 
				  WHEN LEFT([PCRC_EAC],9) = 'PLAT USUA' THEN 'USUARIOS' 
				  ELSE NULL END,
[TRAMO_60MIN] = CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]), '1900-01-01'), 'HH:00:00'),' - ',
                FORMAT(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]) + 1, '1900-01-01'), 'HH:00:00')),
[TRAMO_30MIN] = CASE WHEN DATEPART(MINUTE, [START_YYYYMMDD_HHMMSS]) <= 30 
                     THEN CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]), '1900-01-01'), 'HH:00:00'),' - ',
				          FORMAT(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]), '1900-01-01'), 'HH:30:00'))
                     ELSE CONCAT(FORMAT(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]), '1900-01-01'), 'HH:30:00'),' - ',
				          FORMAT(DATEADD(HOUR,1,(DATEADD(HOUR, DATEPART(HOUR, [START_YYYYMMDD_HHMMSS]), '1900-01-01'))), 'HH:00:00')) END,
[FECHA] = CAST([AGENT_START_YYYYMMDD_HHMMSS] AS DATE),
[HORA] = FORMAT([AGENT_START_YYYYMMDD_HHMMSS],'HH:mm:ss')

