SELECT 
	FECHA [FECHA_START]
	,ANI
	,RUT_USUARIO
INTO 
	[CL_TEMPORALES].[dbo].[TBL_ANI_SIN_RUT]
FROM 
(
SELECT 
	X0.*
FROM
	(
		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM  
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_ATENDIDA] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null

		UNION ALL

		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM  
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_CROSS_INBOUND] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null

		UNION ALL

		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_ABANDONO] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null

		UNION ALL

		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM  
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_TRANSFER] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null

		UNION ALL

		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM  
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_OUTBOUND] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null

		UNION ALL

		SELECT 
			FECHA
			,CALC_NUM_TELEFONO [ANI]
			,ISNULL(RUT_USUARIO,'') RUT_USUARIO
		FROM  
			[CL_TEMPORALES].[dbo].[TBL_TRAFICO_CLEARED] WITH (NOLOCK)
		WHERE 
			RUT_USUARIO=''
			or RUT_USUARIO is null
	)X0
)X1
GROUP BY 
	FECHA
	,ANI
	,RUT_USUARIO
GO

