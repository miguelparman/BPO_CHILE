-- CREAMOS TODOS LOS ANIS SIN RUC
IF EXISTS 
	(
	SELECT * 
	FROM [CL_TEMPORALES].INFORMATION_SCHEMA.TABLES 
	WHERE TABLE_NAME='TBL_ANI_SIN_RUT' AND TABLE_SCHEMA='DBO'
	)
BEGIN
	DROP TABLE [CL_TEMPORALES].[dbo].[TBL_ANI_SIN_RUT]
