-- CRUCE CARTERA ATENDIDA
UPDATE X0
SET SEGMENTO=CASE 
			WHEN X1.SEGME IS NOT NULL THEN X1.SEGME 
			ELSE '' 
		END
FROM 
	[CL_TEMPORALES].[dbo].[TBL_TRAFICO_ATENDIDA] X0 WITH (NOLOCK)
LEFT JOIN 
	CL_CARTERA.DBO.TBL_HISTORIAL_CARTERA X1 WITH (NOLOCK)
ON
	--X0.RUT=X1.RUT_SIN_DV
	REPLACE(REPLACE(X0.RUT,'-',''),'K','1') =REPLACE(REPLACE(X1.RUT_SIN_DV,'-',''),'K','1') 
	AND CONVERT(VARCHAR(8),X0.FECHA,112) BETWEEN X1.FECHA_INICIO AND X1.FECHA_FIN
GO

