-- ACTUALIZAR ATENDIDA SEGMENTO 
UPDATE [CL_TEMPORALES].[dbo].[TBL_TRAFICO_ATENDIDA]
SET [SEGMENTO COLA]=CASE
						WHEN SERVICIO = 'TRIADAS' AND VIRTUAL_QUEUE LIKE '%TRIADAS_NO_CARTERIZADOS%' THEN 'PYME'
						WHEN SERVICIO = 'TRIADAS' AND VIRTUAL_QUEUE LIKE '%TRIADAS_MICRO%' THEN 'MICRO'
						WHEN SERVICIO = 'TRIADAS' AND AGENT_GROUP LIKE '%TRIADAS_NO_CARTERIZADOS%' THEN 'PYME'
						WHEN SERVICIO = 'TRIADAS' AND AGENT_GROUP LIKE '%TRIADAS_MICRO%' THEN 'MICRO'
						WHEN SERVICIO = 'TRIADAS' THEN 'REVISAR'
						ELSE SEGMENTO_AGRUPADO
					END
GO

