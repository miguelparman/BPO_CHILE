INSERT INTO [CL_TRAFICO].[dbo].[TBL_FCR]

SELECT 

	A.*,
	CASE
           WHEN FCR_30min = 0 THEN 'Quiebre en 30 Min'
           WHEN FCR_1h = 0 THEN 'Quiebre en 1 Hora'
           WHEN FCR_2h = 0 THEN 'Quiebre en 2 Horas'
           WHEN FCR_3h = 0 THEN 'Quiebre en 3 Horas'
           WHEN FCR_4h = 0 THEN 'Quiebre en 4 Horas'
           WHEN FCR_6h = 0 THEN 'Quiebre en 6 Horas'
           WHEN FCR_8h = 0 THEN 'Quiebre en 8 Horas'
           WHEN FCR_10h = 0 THEN 'Quiebre en 10 Horas'
           WHEN FCR_12h = 0 THEN 'Quiebre en 12 Horas'
           WHEN FCR_24h = 0 THEN 'Quiebre en 24 Horas'
           WHEN FCR_48h = 0 THEN 'Quiebre en 48 Horas'
           WHEN FCR_72h = 0 THEN 'Quiebre en 72 Horas'
           WHEN FCR_7D = 0 THEN 'Quiebre en 7 Días'
           WHEN FCR_15d = 0 THEN 'Quiebre en 15 Días'
           ELSE 'Sin Quiebre'
       END AS TRAMO_QUIEBRE

FROM(
	SELECT * FROM #TBL_TMP_LLAMADAS_TRIADAS
	UNION ALL
	SELECT * FROM #TBL_TMP_LLAMADAS_CARTERIZADOS
	UNION ALL
	SELECT * FROM #TBL_TMP_LLAMADAS_USUARIOS
	UNION ALL
	SELECT * FROM #TBL_TMP_CHAT_TRIADAS
	UNION ALL
	SELECT * FROM #TBL_TMP_CHAT_CARTERIZADOS)A


