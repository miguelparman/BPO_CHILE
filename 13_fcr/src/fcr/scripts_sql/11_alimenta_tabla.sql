-- PRIMERA BASE: INBOUND TRIADAS

SELECT XB.*,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 1800 THEN 0 ELSE 1 END FCR_30min,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 3600 THEN 0 ELSE 1 END FCR_1h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 7200 THEN 0 ELSE 1 END FCR_2h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 10800 THEN 0 ELSE 1 END FCR_3h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 14400 THEN 0 ELSE 1 END FCR_4h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 21600 THEN 0 ELSE 1 END FCR_6h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 28800 THEN 0 ELSE 1 END FCR_8h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 36000 THEN 0 ELSE 1 END FCR_10h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 43200 THEN 0 ELSE 1 END FCR_12h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 86400 THEN 0 ELSE 1 END FCR_24h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 172800 THEN 0 ELSE 1 END FCR_48h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 259200 THEN 0 ELSE 1 END FCR_72h,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 604800 THEN 0 ELSE 1 END FCR_7D,
CASE WHEN DATEDIFF(SECOND, [FECHA/HORA], [FECHA/HORA-PROXIMO]) <= 1296000 THEN 0 ELSE 1 END FCR_15d


INTO #TBL_TMP_LLAMADAS_TRIADAS

FROM(SELECT XA.*,LEAD ( [FECHA/HORA] ) OVER (  partition by ANI,SERVICIO order by  [FECHA/HORA] asc) [FECHA/HORA-PROXIMO]
	FROM(SELECT CAST([AGENT_START_YYYYMMDD_HHMMSS] AS DATE)FECHA,CAST(CAST([AGENT_START_YYYYMMDD_HHMMSS] AS TIME) AS VARCHAR(8))HORA,ANI,SERVICIO,LOGINID,'LLAMADAS' BASE,CAST([AGENT_START_YYYYMMDD_HHMMSS] AS DATETIME)[FECHA/HORA]
	FROM CL_TRAFICO.dbo.TBL_LLAMADAS_ATENDIDAS_INBOUND 
	WHERE CONVERT(VARCHAR(6),[AGENT_START_YYYYMMDD_HHMMSS],112)>=@PERIODO AND SERVICIO IN ('TRIADAS'))XA)XB

