     IF EXISTS 
(
 SELECT * 
 FROM [CL_SEGUIMIENTO_ACTUAL].INFORMATION_SCHEMA.TABLES 
 WHERE TABLE_NAME='TBL_SEGUIMIENTO_FECHA_BASE' AND TABLE_SCHEMA='DBO'
)
BEGIN
 DROP TABLE [CL_SEGUIMIENTO_ACTUAL].DBO.TBL_SEGUIMIENTO_FECHA_BASE
END  

SET DATEFORMAT DMY

SELECT FORMAT(MAX([Fecha Base]),'dd/MM/yyyy hh:mm tt')[Fecha Base]
INTO [CL_SEGUIMIENTO_ACTUAL].DBO.TBL_SEGUIMIENTO_FECHA_BASE
FROM(SELECT CASE WHEN [Última fecha/hora de modificación de caso] LIKE '%m.%' THEN CAST(REPLACE([Última fecha/hora de modificación de caso],'. m.','M') AS DATETIME) 
   ELSE CONVERT(datetime,[Última fecha/hora de modificación de caso],105) END [Fecha Base]
FROM [CL_TEMPORALES].[dbo].[TBL_SALESFORCE_CASOS])XA